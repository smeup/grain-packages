#!/usr/bin/env python3
"""
Builds index.yaml, the catalog of the grain packages read by Kokos: every package with its versions,
the latest first.

    python3 scripts/build_index.py          # writes index.yaml
    python3 scripts/build_index.py --check  # fails if index.yaml isn't up to date (CI)

The store layout is

    packages/<name>/package.yaml            name, description, publisher
    packages/<name>/versions/<version>.yaml grainVersion, publishedAt, components

The name of a package and its versions are defined by the paths: the files don't repeat them.
"""

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
PACKAGES = ROOT / "packages"
INDEX = ROOT / "index.yaml"

NAME = re.compile(r"^[a-z0-9][a-z0-9-]*$")
# semantic version: major.minor.patch, with an optional pre-release (no build metadata)
VERSION = re.compile(r"^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-([0-9A-Za-z.-]+))?$")

PACKAGE_FIELDS = {"name", "description", "publisher"}
VERSION_FIELDS = {"grainVersion", "publishedAt", "components"}

HEADER = "# Generated by scripts/build_index.py: don't edit\n"


class StoreError(Exception):
    pass


def load(path):
    # every scalar as a string: a version like 1.10 or a timestamp stays as written
    with path.open(encoding="utf-8") as file:
        document = yaml.load(file, Loader=yaml.BaseLoader)
    if not isinstance(document, dict):
        raise StoreError(f"{path.relative_to(ROOT)}: not a yaml mapping")
    return document


def check_fields(path, document, required, allowed):
    missing = required - document.keys()
    unknown = document.keys() - allowed
    if missing:
        raise StoreError(f"{path.relative_to(ROOT)}: missing {sorted(missing)}")
    if unknown:
        raise StoreError(f"{path.relative_to(ROOT)}: unknown {sorted(unknown)}")


def version_key(version):
    """Semantic version precedence: a pre-release precedes its release"""
    major, minor, patch, pre_release = VERSION.match(version).groups()
    identifiers = [] if pre_release is None else [
        (0, int(identifier), "") if identifier.isdigit() else (1, 0, identifier)
        for identifier in pre_release.split(".")
    ]
    return int(major), int(minor), int(patch), pre_release is None, identifiers


def package_entry(directory):
    package_file = directory / "package.yaml"
    if not package_file.is_file():
        raise StoreError(f"{directory.relative_to(ROOT)}: missing package.yaml")
    package = load(package_file)
    check_fields(package_file, package, PACKAGE_FIELDS, PACKAGE_FIELDS)
    if package["name"] != directory.name:
        raise StoreError(f"{package_file.relative_to(ROOT)}: name must be {directory.name}, the name of its folder")
    if not NAME.match(directory.name):
        raise StoreError(f"{directory.relative_to(ROOT)}: invalid package name")

    versions = []
    for version_file in sorted((directory / "versions").glob("*.yaml")):
        version = version_file.stem
        if not VERSION.match(version):
            raise StoreError(f"{version_file.relative_to(ROOT)}: {version} isn't a semantic version (e.g. 1.2.0)")
        document = load(version_file)
        check_fields(version_file, document, VERSION_FIELDS, VERSION_FIELDS)
        versions.append({
            "version": version,
            "grainVersion": document["grainVersion"],
            "publishedAt": document["publishedAt"],
        })
    if not versions:
        raise StoreError(f"{directory.relative_to(ROOT)}: no version")
    versions.sort(key=lambda entry: version_key(entry["version"]), reverse=True)

    return {
        "name": package["name"],
        "description": package["description"],
        "publisher": package["publisher"],
        "versions": versions,
    }


def build_index():
    packages = [package_entry(directory) for directory in sorted(PACKAGES.iterdir()) if directory.is_dir()]
    return HEADER + yaml.safe_dump({"packages": packages}, sort_keys=False, allow_unicode=True)


def main():
    try:
        index = build_index()
    except StoreError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    if "--check" in sys.argv[1:]:
        if not INDEX.is_file() or INDEX.read_text(encoding="utf-8") != index:
            print("error: index.yaml isn't up to date: run python3 scripts/build_index.py", file=sys.stderr)
            return 1
        return 0
    INDEX.write_text(index, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
